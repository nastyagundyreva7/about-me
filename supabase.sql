-- RUD Coins database
-- Run this script once in Supabase SQL Editor.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  last_name text not null,
  first_name text not null,
  middle_name text,
  student_group text not null,
  rudn_email text not null unique,
  role text not null default 'student' check (role in ('student','admin')),
  balance integer not null default 0 check (balance >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  title text not null,
  event_date text not null,
  category text not null,
  topic text,
  base integer not null check (base between 1 and 20),
  level text not null,
  company text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.registrations (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  event_id bigint not null references public.events(id) on delete cascade,
  status text not null default 'registered' check (status in ('registered','confirmed','rejected')),
  participation_level text not null default 'visitor' check (participation_level in ('visitor','participant','active','presenter','winner')),
  coins_awarded integer not null default 0 check (coins_awarded >= 0),
  created_at timestamptz not null default now(),
  confirmed_at timestamptz,
  unique(student_id,event_id)
);

create table if not exists public.coin_transactions (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  amount integer not null,
  kind text not null check (kind in ('event','privilege','adjustment')),
  description text not null,
  registration_id bigint references public.registrations(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.privileges (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  price integer not null check (price > 0),
  image text,
  is_active boolean not null default true
);

create table if not exists public.redemptions (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  privilege_id bigint not null references public.privileges(id),
  price integer not null,
  status text not null default 'requested' check (status in ('requested','issued','cancelled')),
  created_at timestamptz not null default now()
);

-- Automatically create a student profile after email/password registration.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles(id,last_name,first_name,middle_name,student_group,rudn_email)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'last_name',''),
    coalesce(new.raw_user_meta_data->>'first_name',''),
    nullif(new.raw_user_meta_data->>'middle_name',''),
    coalesce(new.raw_user_meta_data->>'student_group',''),
    lower(new.email)
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Keep balance equal to the sum of ledger transactions.
create or replace function public.refresh_balance(p_student uuid)
returns void language plpgsql security definer set search_path = public as $$
begin
  update public.profiles
  set balance = greatest(0, coalesce((select sum(amount) from public.coin_transactions where student_id=p_student),0))
  where id=p_student;
end;
$$;

alter table public.profiles enable row level security;
alter table public.events enable row level security;
alter table public.registrations enable row level security;
alter table public.coin_transactions enable row level security;
alter table public.privileges enable row level security;
alter table public.redemptions enable row level security;

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists(select 1 from public.profiles where id=auth.uid() and role='admin');
$$;

-- Profiles: students see only themselves; admins see all.
drop policy if exists profiles_select on public.profiles;
create policy profiles_select on public.profiles for select using (id=auth.uid() or public.is_admin());
drop policy if exists profiles_update_self on public.profiles;
create policy profiles_update_self on public.profiles for update using (id=auth.uid()) with check (id=auth.uid());
drop policy if exists profiles_admin_update on public.profiles;
create policy profiles_admin_update on public.profiles for update using (public.is_admin()) with check (public.is_admin());

-- Events are public to authenticated users; only admins can change them.
drop policy if exists events_select on public.events;
create policy events_select on public.events for select using (auth.role()='authenticated');
drop policy if exists events_admin_insert on public.events;
create policy events_admin_insert on public.events for insert with check (public.is_admin());
drop policy if exists events_admin_update on public.events;
create policy events_admin_update on public.events for update using (public.is_admin()) with check (public.is_admin());
drop policy if exists events_admin_delete on public.events;
create policy events_admin_delete on public.events for delete using (public.is_admin());

-- Registrations: students create/view their own; admins manage all.
drop policy if exists registrations_select on public.registrations;
create policy registrations_select on public.registrations for select using (student_id=auth.uid() or public.is_admin());
drop policy if exists registrations_insert on public.registrations;
create policy registrations_insert on public.registrations for insert with check (student_id=auth.uid());
drop policy if exists registrations_admin_update on public.registrations;
create policy registrations_admin_update on public.registrations for update using (public.is_admin()) with check (public.is_admin());

-- Ledger: students can read their own ledger; only admins can create adjustments/awards.
drop policy if exists transactions_select on public.coin_transactions;
create policy transactions_select on public.coin_transactions for select using (student_id=auth.uid() or public.is_admin());
drop policy if exists transactions_admin_insert on public.coin_transactions;
create policy transactions_admin_insert on public.coin_transactions for insert with check (public.is_admin());

-- Privileges are visible to authenticated users; only admins edit them.
drop policy if exists privileges_select on public.privileges;
create policy privileges_select on public.privileges for select using (auth.role()='authenticated');
drop policy if exists privileges_admin_insert on public.privileges;
create policy privileges_admin_insert on public.privileges for insert with check (public.is_admin());
drop policy if exists privileges_admin_update on public.privileges;
create policy privileges_admin_update on public.privileges for update using (public.is_admin()) with check (public.is_admin());

-- Redemptions: students create/read their own; admins manage.
drop policy if exists redemptions_select on public.redemptions;
create policy redemptions_select on public.redemptions for select using (student_id=auth.uid() or public.is_admin());
drop policy if exists redemptions_insert on public.redemptions;
create policy redemptions_insert on public.redemptions for insert with check (student_id=auth.uid());
drop policy if exists redemptions_admin_update on public.redemptions;
create policy redemptions_admin_update on public.redemptions for update using (public.is_admin()) with check (public.is_admin());

